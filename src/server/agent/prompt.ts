export function ctxPrefix(p: { mode: Mode; userName: string; role: string; channel: 'web' | 'telegram'; voice?: boolean }) {
  const date = new Date()
  const iso = new Intl.DateTimeFormat('sv-SE', { timeZone: 'Europe/Kyiv' }).format(date)
  return `⟦ctx режим=${p.mode === 'actions' ? 'ДІЇ' : 'ЧАТ'}; сьогодні=${iso} (${dLong(date)}, Київ); користувач=${p.userName} (${p.role}); канал=${p.channel === 'telegram' ? 'Telegram' : 'веб-панель'}${p.voice ? '; ГОЛОС=розпізнаний із голосового, можливі помилки' : ''}⟧`
}

/** Прибирає службовий префікс із тексту для показу користувачу. */
export const stripCtx = (t: string) => t.replace(/^⟦ctx[^⟧]*⟧\n?/, '')
